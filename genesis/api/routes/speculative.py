@router.post("/run")
async def execute_speculative_run(req: RunSpeculativeRequest):
    """Execute accelerated speculative decoding inference run and record telemetry."""
    engine = SpeculativeEngine()
    try:
        cfg = SpeculativeConfig(
            target_model=req.target_model,
            draft_model=req.draft_model,
            lookahead_k=req.lookahead_k,
            acceptance_threshold=req.acceptance_threshold,
            max_tokens=req.max_tokens,
        )
        res = await engine.execute_speculative_run(
            prompt=req.prompt,
            config=cfg,
            run_id=req.run_id,
        )
        return res.to_dict()
    except ValueError as ve:
        raise HTTPException(status_code=422, detail=str(ve))
    except Exception as e:
        raise HTTPException(status_code=400, detail=f"Speculative run failed: {e}")


@router.get("/runs")
async def list_speculative_runs(limit: int = Query(default=20, ge=1, le=100)):
    """List historical speculative decoding runs."""
    engine = SpeculativeEngine()
    runs = engine.list_runs(limit=limit)
    return [r.to_dict() for r in runs]


@router.get("/runs/{run_id}")
async def get_speculative_run(run_id: str):
    """Retrieve details for a specific speculative decoding run."""
    engine = SpeculativeEngine()
    run = engine.get_run(run_id)
    if not run:
        raise HTTPException(status_code=404, detail=f"Speculative run '{run_id}' not found")
    return run.to_dict()
