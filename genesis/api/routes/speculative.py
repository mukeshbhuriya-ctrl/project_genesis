"""
REST API routes for Self-Speculative Decoding Engine (Phase 14).
"""

from __future__ import annotations

from typing import Any, Optional

from fastapi import APIRouter, HTTPException, Query
from pydantic import BaseModel, Field

from genesis.models.speculative import (
    SpeculativeConfig,
    SpeculativeEngine,
)

router = APIRouter(prefix="/speculative", tags=["Self-Speculative Decoding"])


class RunSpeculativeRequest(BaseModel):
    prompt: str = Field(..., min_length=1, description="Prompt text to generate with speculative decoding")
    target_model: str = Field(default="qwen2.5:7b", description="Primary target verification model")
    draft_model: str = Field(default="qwen2.5-coder:1.5b-base", description="Lightweight draft proposal model")
    lookahead_k: int = Field(default=4, ge=1, le=8, description="Number of lookahead tokens generated by draft model per verification pass")
    acceptance_threshold: float = Field(default=0.75, ge=0.1, le=1.0, description="Rejection sampling probability ratio threshold")
    max_tokens: int = Field(default=64, ge=8, le=512, description="Maximum total generated tokens")
    run_id: Optional[str] = Field(default=None, description="Optional custom run ID")


